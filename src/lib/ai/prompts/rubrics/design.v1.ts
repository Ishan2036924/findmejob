export const DESIGN_RUBRIC = `## RUBRIC: Design (design)
Version: ${DESIGN_RUBRIC_VERSION}

Evaluate the candidate against these dimensions for the seniority specified in their profile.

### DIMENSIONS (weights — must sum to 100%)

- craft_quality (30%): Visual fundamentals (typography, hierarchy, color), interaction design, motion sensitivity, prototyping rigor, attention to details. Reflected in portfolio if linked.
- process_rigor (25%): Research-to-design pipeline, iteration discipline, design systems thinking, accessibility (WCAG), usability testing, design critique participation.
- business_alignment (20%): Impact metric ownership, partnership with PM + eng on tradeoffs, understanding of constraints (time, scope, technical feasibility), shipping mindset over pixel-perfection-only.
- communication (15%): Critique articulation, design rationale writing, presenting to stakeholders + execs, cross-team alignment.
- trajectory (10%): IC → senior IC → lead progression, domain expansion (e.g., visual + product + motion), tool/method depth growth.

### SENIORITY EXPECTATIONS

- intern / entry: craft_quality weighted highest. Process rigor lighter but should show some methodology.
- mid: must own a product surface end-to-end with shipped work. Design system contribution expected.
- senior+: cross-team design leadership. Mentoring evidence. Strategic design (vision, north-star concepts) expected.

### GAP DETECTION (specific things to flag if absent)

- No portfolio link or only static screenshots without context
- "Designed the UI" with no problem framing, user research, or outcome
- No accessibility considerations mentioned anywhere
- No design system contribution or component-thinking for mid+
- Tools listing (Figma, Sketch) with no process or method context
- No metric impact (engagement, conversion, satisfaction) anywhere
- No cross-functional partnership described

### STRENGTH SIGNALS (specific things to credit if present)

- Strong portfolio with case studies showing problem → process → outcome
- Design system authorship or major contribution
- Quantified outcome (X% conversion lift, Y% reduction in support tickets)
- Accessibility leadership (audit ownership, AA/AAA compliance)
- Speaking, writing, or open-source design tooling
- Mentorship and design critique facilitation`;
